def single_link_obp_analytical(lam, c, T, t_buffer, F0=0.9):
    prob_arrival = 1 - np.exp(-lam * t_buffer)

    if prob_arrival == 0:
        return 0.5, 0.0, 0.0

    avg_t_gen = (1/lam) * (1 - (1 + lam*t_buffer) * np.exp(-lam*t_buffer)) / prob_arrival

    F_at_buffer = 0.25 + (F0 - 0.25) * np.exp(-2 * (t_buffer - avg_t_gen) / c)
    F_at_T = compute_fidelity(F_at_buffer, T - t_buffer, c)

    success_rate = prob_arrival
    R = success_rate * coherent_information(F_at_T)

    return F_at_T, R, success_rate

def find_optimal_buffer_time_single_link_analytical(lam, c, T):
    t_values = np.linspace(0.01 * T, T, 50)
    best_t = T
    best_Ic = 0
    for t_buf in t_values:
        _, R, _ = single_link_obp_analytical(lam, c, T, t_buf, F0=0.9)
        if R > best_Ic:
            best_Ic = R
            best_t = t_buf
    return best_t

def discard_oldest(n_samples, lam, c, T, samples):
    t1a, t1b, t2a, t2b = samples['t_l1_1'], samples['t_l1_2'], samples['t_l2_1'], samples['t_l2_2']
    F_final = np.zeros(n_samples)
    used = np.zeros(n_samples, dtype=bool)

    for i in range(n_samples):
        link1_times = [t for t in [t1a[i], t1b[i]] if t < T]
        link2_times = [t for t in [t2a[i], t2b[i]] if t < T]
        if len(link1_times) >= 1 and len(link2_times) >= 1:
            F1 = raw_fidelity(max(link1_times), T, c)
            F2 = raw_fidelity(max(link2_times), T, c)
            F_final[i] = swapped_fidelity(F1, F2)
            used[i] = True

    F_mean = np.mean(F_final[used]) if np.sum(used) > 0 else 0.0
    success_rate = np.sum(used) / n_samples
    mean_Ic = coherent_information_vectorized(F_mean) * success_rate
    std_Ic = 0.0
    return mean_Ic, std_Ic, F_mean, success_rate

def double_link_obp_fixed_buffer(n_samples, lam, c, T, samples, t_buffer_l1, t_buffer_l2):
    t1a, t1b, t2a, t2b = samples['t_l1_1'], samples['t_l1_2'], samples['t_l2_1'], samples['t_l2_2']
    F_final = np.zeros(n_samples)
    used = np.zeros(n_samples, dtype=bool)

    for i in range(n_samples):
        link1_times = [t for t in [t1a[i], t1b[i]] if t < t_buffer_l1]
        link2_times = [t for t in [t2a[i], t2b[i]] if t < t_buffer_l2]

        if len(link1_times) >= 1 and len(link2_times) >= 1:
            t_first_l1 = link1_times[0]
            t_first_l2 = link2_times[0]

            F1_at_buffer = raw_fidelity(t_first_l1, t_buffer_l1, c)
            F2_at_buffer = raw_fidelity(t_first_l2, t_buffer_l2, c)

            t_swap = max(t_buffer_l1, t_buffer_l2)
            F1_at_swap = compute_fidelity(F1_at_buffer, t_swap - t_buffer_l1, c)
            F2_at_swap = compute_fidelity(F2_at_buffer, t_swap - t_buffer_l2, c)

            F_swap = swapped_fidelity(F1_at_swap, F2_at_swap)
            F_at_T = compute_fidelity(F_swap, T - t_swap, c)

            F_final[i] = F_at_T
            used[i] = True

    F_mean = np.mean(F_final[used]) if np.sum(used) > 0 else 0.5
    success_rate = np.sum(used) / n_samples
    mean_Ic = coherent_information_vectorized(F_mean) * success_rate
    std_Ic = 0.0

    return mean_Ic, std_Ic, F_mean, success_rate

def find_optimal_buffer_times_double_link(lam, c, T, samples, n_samples):
    t_values = np.linspace(0.01 * T, T, 10)
    best_t1, best_t2 = T, T
    best_Ic = 0

    for t1 in t_values:
        for t2 in t_values:
            mean_Ic, _, _, _ = double_link_obp_fixed_buffer(n_samples, lam, c, T, samples, t1, t2)
            if mean_Ic > best_Ic:
                best_Ic = mean_Ic
                best_t1 = t1
                best_t2 = t2

    return best_t1, best_t2


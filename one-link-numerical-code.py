        p_succ_term3_inner_low = cL_low * (c*(8*F0*F0 - 4*F0 - 13)*L_low + 54) - 54
        p_succ_term3_low = (2 * exp2LT_low * p_succ_term3_inner_low) / ((cL_low-2)*(cL_low-2))
        p_succ_term4_low = 18 * expLT_low + 9
        p_succ_mean_low = (1/18) * (p_succ_term1_low + p_succ_term2_low + p_succ_term3_low + p_succ_term4_low)

        L_high = lam_high
        expLT_high = np.exp(-L_high * T_high)
        exp2LT_high = np.exp(-2 * L_high * T_high)
        exp2Tc_high = np.exp(-2 * T_high / c)
        expSum_high = np.exp(-T_high * (2/c + L_high))
        cL_high = c * L_high


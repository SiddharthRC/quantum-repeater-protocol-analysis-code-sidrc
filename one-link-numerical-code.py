        num2_high = 6 * c * (4*F0 - 1) * L_high * (cL_high - 2) * exp2Tc_high
        num3_high = -20 * c * (4*F0 - 1) * L_high * (2*c*(F0-1)*L_high + 3) * expSum_high
        num4_high = -12 * (cL_high - 2) * expLT_high * (2*c*(F0-1)*L_high + 3)
        num5_inner_high = 8*cL_high*(10*F0*(c*(F0-2)*L_high + 3) + cL_high + 6) - 108
        num5_high = exp2LT_high * num5_inner_high
        num6_high = 9 * (cL_high - 2) * (cL_high - 2)
        numerator_high = num1_high + num2_high + num3_high + num4_high + num5_high + num6_high

        denom_factor_high = 4 * (cL_high - 2) * (cL_high - 2)
        denom1_high = (c*c * (1-4*F0)*(1-4*F0) * L_high*L_high * np.exp(-4*T_high/c)) / ((cL_high-2)*(cL_high-2))
        denom2_high = -(2 * c*c * (1-4*F0)*(1-4*F0) * L_high*L_high * expSum_high) / ((cL_high-2)*(cL_high-2))
        denom3_inner_high = cL_high * (c * (8*F0*F0 - 4*F0 - 13) * L_high + 54) - 54
        denom3_high = (2 * exp2LT_high * denom3_inner_high) / ((cL_high-2)*(cL_high-2))
        denom4_high = 18 * expLT_high + 9
        denominator_high = denom_factor_high * (denom1_high + denom2_high + denom3_high + denom4_high)
        Fbar_high = numerator_high / (denominator_high + eps)

        p_succ_term1_high = (c*c * (1-4*F0)*(1-4*F0) * L_high*L_high * np.exp(-4*T_high/c)) / ((cL_high-2)*(cL_high-2))
        p_succ_term2_high = -(2 * c*c * (1-4*F0)*(1-4*F0) * L_high*L_high * expSum_high) / ((cL_high-2)*(cL_high-2))

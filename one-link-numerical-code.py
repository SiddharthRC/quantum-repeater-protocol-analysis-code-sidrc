        p_succ_term3_high = (2 * exp2LT_high * p_succ_term3_inner_high) / ((cL_high-2)*(cL_high-2))
        p_succ_term4_high = 18 * expLT_high + 9
        p_succ_mean_high = (1/18) * (p_succ_term1_high + p_succ_term2_high + p_succ_term3_high + p_succ_term4_high)

        alpha = (lam - lam_low) / (lam_high - lam_low)
        Fbar = Fbar_low * (1 - alpha) + Fbar_high * alpha
        p_succ_mean = p_succ_mean_low * (1 - alpha) + p_succ_mean_high * alpha

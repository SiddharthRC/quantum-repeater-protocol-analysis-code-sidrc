def analytic_repeated_swap(F0, N):
    arr = [F0] * N
    while len(arr) > 1:
        arr = [swapped_fidelity(arr[j], arr[j+1]) if j+1 < len(arr) else arr[j] for j in range(0, len(arr), 2)]
    return arr[0]


def coherent_information(F):
    F = np.clip(F, 1e-12, 1 - 1e-12)
    lambda1 = F
    lambda_rest = (1 - F) / 3
    eigs = np.array([lambda1, lambda_rest, lambda_rest, lambda_rest])
    S = -np.sum(eigs * np.log2(eigs + 1e-12))
    return np.maximum(0, 1 - S)

def isotropic_purification_pairwise(F1, F2):
    num = F1 * F2 + (1/9) * (1 - F1) * (1 - F2)
    denom = (F1 * F2 + (1/3) * F1 * (1 - F2) + (1/3) * F2 * (1 - F1) + (5/9) * (1 - F1) * (1 - F2))
    return np.clip(num / denom, 0, 1)

def discard_oldest_analytical(lam, c, T, F0=0.9):
    eps = 1e-8
    expLT = np.exp(-lam * T)
    exp2LT = np.exp(-2 * lam * T)
    exp2Tc = np.exp(-2 * T / c)
    F0_eff = F0 - 0.25

    term1 = 0.25 - 0.25 * exp2LT
    coeff = 2 * lam * F0_eff

    denom1 = lam - 2/c
    if abs(denom1) < eps:
        bracket1 = T * (expLT + 1) * exp2Tc
    else:
        bracket1 = (expLT + 1) * (exp2Tc - expLT) / denom1

    denom2 = 2*lam - 2/c
    if abs(denom2) < eps:
        bracket2 = T * exp2Tc
    else:
        bracket2 = (exp2Tc - exp2LT) / denom2

    term2 = coeff * (bracket1 - bracket2)

    Fbar = (term1 + term2) / (1 - exp2LT + eps)
    Fbar = np.clip(Fbar, 0, 1)
    success_rate = 1 - exp2LT
    R = success_rate * coherent_information(Fbar)

    return Fbar, R, success_rate

def distill_alap_analytical(lam, c, T, F0=0.9):
    eps = 1e-8
    L = lam
    lam_orig = lam

    if abs(c * L - 2) < 0.05:
        delta = 0.02
        lam_low = (2.0 - delta) / c
        lam_high = (2.0 + delta) / c
        T_low = 2.0 / lam_low
        T_high = 2.0 / lam_high

        L_low = lam_low
        expLT_low = np.exp(-L_low * T_low)
        exp2LT_low = np.exp(-2 * L_low * T_low)
        exp2Tc_low = np.exp(-2 * T_low / c)
        expSum_low = np.exp(-T_low * (2/c + L_low))
        cL_low = c * L_low

        num1_low = 5 * c * c * (1 - 4*F0) * (1 - 4*F0) * L_low * L_low * np.exp(-4*T_low/c)
        num2_low = 6 * c * (4*F0 - 1) * L_low * (cL_low - 2) * exp2Tc_low
        num3_low = -20 * c * (4*F0 - 1) * L_low * (2*c*(F0-1)*L_low + 3) * expSum_low
        num4_low = -12 * (cL_low - 2) * expLT_low * (2*c*(F0-1)*L_low + 3)
        num5_inner_low = 8*cL_low*(10*F0*(c*(F0-2)*L_low + 3) + cL_low + 6) - 108
        num5_low = exp2LT_low * num5_inner_low
        num6_low = 9 * (cL_low - 2) * (cL_low - 2)
        numerator_low = num1_low + num2_low + num3_low + num4_low + num5_low + num6_low

        denom_factor_low = 4 * (cL_low - 2) * (cL_low - 2)
        denom1_low = (c*c * (1-4*F0)*(1-4*F0) * L_low*L_low * np.exp(-4*T_low/c)) / ((cL_low-2)*(cL_low-2))
        denom2_low = -(2 * c*c * (1-4*F0)*(1-4*F0) * L_low*L_low * expSum_low) / ((cL_low-2)*(cL_low-2))
        denom3_inner_low = cL_low * (c * (8*F0*F0 - 4*F0 - 13) * L_low + 54) - 54
        denom3_low = (2 * exp2LT_low * denom3_inner_low) / ((cL_low-2)*(cL_low-2))
        denom4_low = 18 * expLT_low + 9
        denominator_low = denom_factor_low * (denom1_low + denom2_low + denom3_low + denom4_low)
        Fbar_low = numerator_low / (denominator_low + eps)

        p_succ_term1_low = (c*c * (1-4*F0)*(1-4*F0) * L_low*L_low * np.exp(-4*T_low/c)) / ((cL_low-2)*(cL_low-2))

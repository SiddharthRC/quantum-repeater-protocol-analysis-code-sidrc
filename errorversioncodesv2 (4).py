def raw_fidelity(t_gen, t_total, tau):
    A = 1/4
    B = F_INIT - A
    return np.clip(A + B * np.exp(-2 * (t_total - t_gen) / tau), 0, 1)

def compute_fidelity(F_init, t_idle, tau):
    A = 1/4
    B = F_init - A
    return np.clip(A + B * np.exp(-2 * t_idle / tau), 0, 1)

def isotropic_purification_pairwise(F1, F2, p_gate=1.0, p_meas=1.0):

    e1 = (1 - F1) / 3
    e2 = (1 - F2) / 3

    if p_gate == 1.0 and p_meas == 1.0:
        num = F1 * F2 + (1/9) * (1 - F1) * (1 - F2)
        denom = (F1 * F2 + (1/3) * F1 * (1 - F2) + (1/3) * F2 * (1 - F1) +
                 (5/9) * (1 - F1) * (1 - F2))
        F_out = np.clip(num / denom, 0, 1)
        p_success = denom
    else:
        eta = p_meas
        p = p_gate

        p_success = (p**2 * (eta**2 + (1 - eta)**2) *
                     (F1*F2 + F1*e2 + e1*F2 + 5*e1*e2) +
                     2 * p**2 * eta * (1 - eta) *
                     (2*F1*e2 + 2*e1*F2 + 4*e1*e2) +
                     (1 - p**2) / 2)

        numerator = ((eta**2 + (1 - eta)**2) * (F1*F2 + e1*e2) +
                     2 * eta * (1 - eta) * (F1*e2 + e1*e2) +
                     (1 - p**2) / (8 * p**2))

        denominator = ((eta**2 + (1 - eta)**2) *
                       (F1*F2 + F1*e2 + e1*F2 + 5*e1*e2) +
                       2 * eta * (1 - eta) *
                       (2*F1*e2 + 2*e1*F2 + 4*e1*e2) +
                       (1 - p**2) / (2 * p**2))

        F_out = np.clip(numerator / denominator, 0, 1)

    return F_out, p_success

def swapped_fidelity(F1, F2, p_gate=1.0, p_meas=1.0):
    if p_gate == 1.0 and p_meas == 1.0:
        return np.clip(F1 * F2 + (1 - F1) * (1 - F2) / 3, 0, 1)
    else:
        eta = p_meas
        p = p_gate
        e1 = (1 - F1) / 3
        e2 = (1 - F2) / 3

        F_swap = ((1 - p) / 4 +
                  p * (eta**2 * (F1*F2 + 3*e1*e2) +
                       (1 - eta**2) * (F1*e2 + e1*F2 + 2*e1*e2)))

        return np.clip(F_swap, 0, 1)

def coherent_information_vectorized(F):
    λ1 = F
    λ_rest = (1 - F) / 3
    eigs = np.stack([λ1, λ_rest, λ_rest, λ_rest], axis=-1)
    S = -np.sum(eigs * np.log2(eigs + 1e-12), axis=-1)
    return np.maximum(0, 1 - S)

def state_availability(t1a, t1b, t2a, t2b, T):
    available = np.zeros(len(t1a), dtype=int)
    available += (t1a < T).astype(int) + (t1b < T).astype(int) + (t2a < T).astype(int) + (t2b < T).astype(int)
    return available

def sample_link_arrivals(n_samples, lam):
    s = np.random.exponential(scale=1.0 / lam, size=(2, 2, n_samples))
    s.sort(axis=1)
    return {'t_l1_1': s[0, 0], 't_l1_2': s[0, 1],
            't_l2_1': s[1, 0], 't_l2_2': s[1, 1]}


def _weighted_summary(valid, weight, F_final, n_samples):
    w = np.where(valid, weight, 0.0)
    total = w.sum()
    if total <= 0:
        return 0.0, 0.0, 0.0, 0.0
    F_mean = float((w * F_final).sum() / total)
    P_succ = float(w.mean())
    mean_Ic = float(coherent_information_vectorized(F_mean) * P_succ)
    return mean_Ic, 0.0, F_mean, P_succ


def discard_oldest(n_samples, lam, tau, T, samples, p_gate=1.0, p_meas=1.0):
    a1, a2 = samples['t_l1_1'], samples['t_l1_2']
    b1, b2 = samples['t_l2_1'], samples['t_l2_2']
    valid = (a1 < T) & (b1 < T)
    a_new = np.where(a2 < T, a2, a1)
    b_new = np.where(b2 < T, b2, b1)
    F_final = swapped_fidelity(raw_fidelity(a_new, T, tau),
                               raw_fidelity(b_new, T, tau), p_gate, p_meas)
    return _weighted_summary(valid, np.ones(n_samples), F_final, n_samples)


def distill_then_swap(n_samples, lam, tau, T, samples, distill_strategy, swap_strategy,
                      p_gate=1.0, p_meas=1.0):
    # NOTE (correction): the ASAP branch previously set each link's distillation
    # time to link_pairs[1], the second arrival, and then swapped at the max of
    # those. A pair arriving after both links were first ready could therefore
    # postpone a swap that the stated policy requires to happen immediately, so
    # the schedule used information not available at decision time. The swap
    # time is now fixed at max(a1, b1) first, and a link is distilled only if
    # its second pair has already arrived by then.
    a1, a2 = samples['t_l1_1'], samples['t_l1_2']
    b1, b2 = samples['t_l2_1'], samples['t_l2_2']
    valid = (a1 < T) & (b1 < T)

    if distill_strategy == 'ASAP' and swap_strategy == 'ASAP':
        t_swap = np.maximum(a1, b1)
        distill_a = valid & (a2 <= t_swap)
        distill_b = valid & (b2 <= t_swap)

        Fa_d, pa = isotropic_purification_pairwise(
            raw_fidelity(a1, a2, tau), np.full_like(a1, F_INIT), p_gate, p_meas)
        Fb_d, pb = isotropic_purification_pairwise(
            raw_fidelity(b1, b2, tau), np.full_like(b1, F_INIT), p_gate, p_meas)

        Fa = np.where(distill_a, compute_fidelity(Fa_d, t_swap - a2, tau),
                      raw_fidelity(a1, t_swap, tau))
        Fb = np.where(distill_b, compute_fidelity(Fb_d, t_swap - b2, tau),
                      raw_fidelity(b1, t_swap, tau))
        weight = np.where(distill_a, pa, 1.0) * np.where(distill_b, pb, 1.0)
        F_final = compute_fidelity(
            swapped_fidelity(Fa, Fb, p_gate, p_meas), T - t_swap, tau)
        return _weighted_summary(valid, weight, F_final, n_samples)

    def link_at_T(x1, x2):
        has_two = x2 < T
        if distill_strategy == 'ASAP':
            F_d, p_d = isotropic_purification_pairwise(
                raw_fidelity(x1, x2, tau), np.full_like(x1, F_INIT), p_gate, p_meas)
            F_two = compute_fidelity(F_d, T - x2, tau)
        else:
            F_d, p_d = isotropic_purification_pairwise(
                raw_fidelity(x1, T, tau), raw_fidelity(x2, T, tau), p_gate, p_meas)
            F_two = F_d
        return (np.where(has_two, F_two, raw_fidelity(x1, T, tau)),
                np.where(has_two, p_d, 1.0))

    Fa, pa = link_at_T(a1, a2)
    Fb, pb = link_at_T(b1, b2)
    F_final = swapped_fidelity(Fa, Fb, p_gate, p_meas)
    return _weighted_summary(valid, pa * pb, F_final, n_samples)


def _swap_pair(x, y, tau, asap, T, p_gate, p_meas):
    t = np.maximum(x, y) if asap else np.full_like(x, T)
    F = swapped_fidelity(raw_fidelity(x, t, tau), raw_fidelity(y, t, tau),
                         p_gate, p_meas)
    return t, F


def swap_then_distill(n_samples, lam, tau, T, samples, swap_strategy, distill_strategy,
                      p_gate=1.0, p_meas=1.0):
    # NOTE (correction): distillation requires two copies of entanglement shared
    # between the SAME two end nodes, so the second copy must come from a second
    # full swap, which itself requires a second elementary pair on EACH segment.
    # NOTE (correction): the second swap was previously performed at T, with the
    # elementary pairs decayed to T before being swapped, so only the first of
    # the two swaps was actually ASAP. Both swaps now occur as soon as their
    # inputs exist, and only the final distillation is deferred for the D-ALAP
    # variants.
    a1, a2 = samples['t_l1_1'], samples['t_l1_2']
    b1, b2 = samples['t_l2_1'], samples['t_l2_2']
    valid = (a1 < T) & (b1 < T)
    has_second = valid & (a2 < T) & (b2 < T)

    swap_asap = (swap_strategy == 'ASAP')
    t1, F1 = _swap_pair(a1, b1, tau, swap_asap, T, p_gate, p_meas)
    t2, F2 = _swap_pair(a2, b2, tau, swap_asap, T, p_gate, p_meas)

    if distill_strategy == 'ASAP':
        t_d = np.maximum(t1, t2)
        F_d, p_d = isotropic_purification_pairwise(
            compute_fidelity(F1, t_d - t1, tau),
            compute_fidelity(F2, t_d - t2, tau), p_gate, p_meas)
        F_if_two = compute_fidelity(F_d, T - t_d, tau)
    else:
        F_d, p_d = isotropic_purification_pairwise(
            compute_fidelity(F1, T - t1, tau),
            compute_fidelity(F2, T - t2, tau), p_gate, p_meas)
        F_if_two = F_d

    F_one = compute_fidelity(F1, T - t1, tau)
    F_final = np.where(has_second, F_if_two, F_one)
    weight = np.where(has_second, p_d, 1.0)
    return _weighted_summary(valid, weight, F_final, n_samples)


def discard_oldest_distribution(n_samples, lam, tau, T, samples, p_gate=1.0, p_meas=1.0):
    a1, a2 = samples['t_l1_1'], samples['t_l1_2']
    b1, b2 = samples['t_l2_1'], samples['t_l2_2']
    valid = (a1 < T) & (b1 < T)
    a_new = np.where(a2 < T, a2, a1)
    b_new = np.where(b2 < T, b2, b1)
    F = swapped_fidelity(raw_fidelity(a_new, T, tau),
                         raw_fidelity(b_new, T, tau), p_gate, p_meas)[valid]
    return F, coherent_information_vectorized(F)


def swap_then_distill_distribution(n_samples, lam, tau, T, samples,
                                   swap_strategy, distill_strategy,
                                   p_gate=1.0, p_meas=1.0):
    # NOTE (correction): same topology and second-swap timing fixes as in
    # swap_then_distill. The distillation attempt is rejection-sampled so that
    # only actual successful outputs enter the histogram.
    a1, a2 = samples['t_l1_1'], samples['t_l1_2']
    b1, b2 = samples['t_l2_1'], samples['t_l2_2']
    valid = (a1 < T) & (b1 < T)
    has_second = valid & (a2 < T) & (b2 < T)

    swap_asap = (swap_strategy == 'ASAP')
    t1, F1 = _swap_pair(a1, b1, tau, swap_asap, T, p_gate, p_meas)
    t2, F2 = _swap_pair(a2, b2, tau, swap_asap, T, p_gate, p_meas)

    if distill_strategy == 'ASAP':
        t_d = np.maximum(t1, t2)
        F_d, p_d = isotropic_purification_pairwise(
            compute_fidelity(F1, t_d - t1, tau),
            compute_fidelity(F2, t_d - t2, tau), p_gate, p_meas)
        F_if_two = compute_fidelity(F_d, T - t_d, tau)
    else:
        F_d, p_d = isotropic_purification_pairwise(
            compute_fidelity(F1, T - t1, tau),
            compute_fidelity(F2, T - t2, tau), p_gate, p_meas)
        F_if_two = F_d

    F_one = compute_fidelity(F1, T - t1, tau)
    accept = np.random.uniform(0.0, 1.0, size=n_samples) < p_d
    keep = valid & np.where(has_second, accept, True)
    F = np.where(has_second, F_if_two, F_one)[keep]
    return F, coherent_information_vectorized(F)


def shared_bin_edges(*datasets, bins=60):
    pooled = np.concatenate([np.asarray(d).ravel() for d in datasets
                             if np.asarray(d).size > 0])
    if pooled.size == 0:
        return np.linspace(0.0, 1.0, bins + 1)
    lo, hi = float(pooled.min()), float(pooled.max())
    if hi <= lo:
        hi = lo + 1e-9
    return np.linspace(lo, hi, bins + 1)


def analytic_repeated_swap(F0, N, p_gate=1.0, p_meas=1.0):
    arr = [F0] * N
    while len(arr) > 1:
        arr = [swapped_fidelity(arr[j], arr[j+1], p_gate, p_meas) if j+1 < len(arr)
               else arr[j] for j in range(0, len(arr), 2)]
    return arr[0]


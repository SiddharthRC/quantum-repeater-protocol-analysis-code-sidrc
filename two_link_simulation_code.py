def raw_fidelity(t_gen, t_total, c):
    A = 1/4
    B = (3/4) * np.exp(-2 * t_total / c)
    return np.clip(A + B * np.exp(2 * t_gen / c), 0, 1)

def compute_fidelity(F_init, t_idle, c):
    A = 1/4
    B = F_init - A
    return np.clip(A + B * np.exp(-2 * t_idle / c), 0, 1)

def isotropic_purification_pairwise(F1, F2):
    num = F1 * F2 + (1/9) * (1 - F1) * (1 - F2)
    denom = (F1 * F2 + (1/3) * F1 * (1 - F2) + (1/3) * F2 * (1 - F1) + (5/9) * (1 - F1) * (1 - F2))
    return np.clip(num / denom, 0, 1)

def swapped_fidelity(F1, F2):
    return np.clip(F1 * F2 + (1 - F1) * (1 - F2) / 3, 0, 1)

def coherent_information_vectorized(F):
    λ1 = F
    λ_rest = (1 - F) / 3
    eigs = np.stack([λ1, λ_rest, λ_rest, λ_rest], axis=-1)
    S = -np.sum(eigs * np.log2(eigs + 1e-12), axis=-1)
    return np.maximum(0, 1 - S)

def state_availability(t1a, t1b, t2a, t2b, T):
    available = np.zeros(len(t1a), dtype=int)
    available += (t1a < T).astype(int) + (t1b < T).astype(int) + (t2a < T).astype(int) + (t2b < T).astype(int)
    return available

def discard_oldest(n_samples, lam, c, T, samples):
    t1a, t1b, t2a, t2b = samples['t_l1_1'], samples['t_l1_2'], samples['t_l2_1'], samples['t_l2_2']
    F_final = np.zeros(n_samples)
    used = np.zeros(n_samples, dtype=bool)

    for i in range(n_samples):
        link1_times = [t for t in [t1a[i], t1b[i]] if t < T]
        link2_times = [t for t in [t2a[i], t2b[i]] if t < T]
        if len(link1_times) >= 1 and len(link2_times) >= 1:
            F1 = raw_fidelity(max(link1_times), T, c)
            F2 = raw_fidelity(max(link2_times), T, c)
            F_final[i] = swapped_fidelity(F1, F2)
            used[i] = True

    F_mean = np.mean(F_final[used]) if np.sum(used) > 0 else 0.0
    success_rate = np.sum(used) / n_samples
    mean_Ic = coherent_information_vectorized(F_mean) * success_rate
    Ic_all = coherent_information_vectorized(F_final[used]) if np.sum(used) > 0 else np.array([])
    std_Ic = np.std(Ic_all) if len(Ic_all) > 0 else 0.0
    return mean_Ic, std_Ic, F_mean, success_rate

def distill_then_swap(n_samples, lam, c, T, samples, distill_strategy, swap_strategy):
    t1a, t1b, t2a, t2b = samples['t_l1_1'], samples['t_l1_2'], samples['t_l2_1'], samples['t_l2_2']
    avail = state_availability(t1a, t1b, t2a, t2b, T)
    valid = avail >= 2
    F_final = np.zeros_like(t1a)
    p_success_all = np.ones(n_samples)
    used = valid.copy()

    for i in np.where(valid)[0]:
        link1_pairs = sorted([t for t in [t1a[i], t1b[i]] if t < T])
        link2_pairs = sorted([t for t in [t2a[i], t2b[i]] if t < T])
        ready_l1, ready_l2 = len(link1_pairs), len(link2_pairs)

        if distill_strategy == 'ASAP':
            p_success_total = 1.0

            if ready_l1 >= 2:
                t_dist_l1 = link1_pairs[1]
                Fa = raw_fidelity(link1_pairs[0], t_dist_l1, c)
                Fb = raw_fidelity(link1_pairs[1], t_dist_l1, c)
                F1 = isotropic_purification_pairwise(Fa, Fb)
                p_success_l1 = Fa * Fb + (1/3) * Fa * (1 - Fb) + (1/3) * Fb * (1 - Fa) + (5/9) * (1 - Fa) * (1 - Fb)
                p_success_total *= p_success_l1
            elif ready_l1 == 1:
                t_dist_l1 = link1_pairs[0]
                F1 = raw_fidelity(link1_pairs[0], t_dist_l1, c)
            else:
                used[i] = False
                continue

            if ready_l2 >= 2:
                t_dist_l2 = link2_pairs[1]
                Fa = raw_fidelity(link2_pairs[0], t_dist_l2, c)
                Fb = raw_fidelity(link2_pairs[1], t_dist_l2, c)
                F2 = isotropic_purification_pairwise(Fa, Fb)
                p_success_l2 = Fa * Fb + (1/3) * Fa * (1 - Fb) + (1/3) * Fb * (1 - Fa) + (5/9) * (1 - Fa) * (1 - Fb)
                p_success_total *= p_success_l2
            elif ready_l2 == 1:
                t_dist_l2 = link2_pairs[0]
                F2 = raw_fidelity(link2_pairs[0], t_dist_l2, c)
            else:
                used[i] = False
                continue

            if swap_strategy == 'ASAP':
                t_swap = max(t_dist_l1, t_dist_l2)
                F1_at_swap = compute_fidelity(F1, t_swap - t_dist_l1, c)
                F2_at_swap = compute_fidelity(F2, t_swap - t_dist_l2, c)
                F_swap = swapped_fidelity(F1_at_swap, F2_at_swap)
                F_final[i] = compute_fidelity(F_swap, T - t_swap, c)
            else:
                F1 = compute_fidelity(F1, T - t_dist_l1, c)
                F2 = compute_fidelity(F2, T - t_dist_l2, c)
                F_final[i] = swapped_fidelity(F1, F2)

            p_success_all[i] = p_success_total

        else:
            p_success_total = 1.0

            if ready_l1 >= 2:
                Fa = raw_fidelity(link1_pairs[0], T, c)
                Fb = raw_fidelity(link1_pairs[1], T, c)
                F1 = isotropic_purification_pairwise(Fa, Fb)
                p_success_l1 = Fa * Fb + (1/3) * Fa * (1 - Fb) + (1/3) * Fb * (1 - Fa) + (5/9) * (1 - Fa) * (1 - Fb)
                p_success_total *= p_success_l1
            elif ready_l1 == 1:
                F1 = raw_fidelity(link1_pairs[0], T, c)
            else:
                used[i] = False
                continue

            if ready_l2 >= 2:
                Fa = raw_fidelity(link2_pairs[0], T, c)
                Fb = raw_fidelity(link2_pairs[1], T, c)
                F2 = isotropic_purification_pairwise(Fa, Fb)
                p_success_l2 = Fa * Fb + (1/3) * Fa * (1 - Fb) + (1/3) * Fb * (1 - Fa) + (5/9) * (1 - Fa) * (1 - Fb)
                p_success_total *= p_success_l2
            elif ready_l2 == 1:
                F2 = raw_fidelity(link2_pairs[0], T, c)
            else:
                used[i] = False
                continue

            F_final[i] = swapped_fidelity(F1, F2)
            p_success_all[i] = p_success_total

    F_mean = np.mean(F_final[used]) if np.sum(used) > 0 else 0.0
    success_rate = np.sum(used) / n_samples
    mean_p_success = np.mean(p_success_all[used]) if np.sum(used) > 0 else 0.0
    mean_Ic = coherent_information_vectorized(F_mean) * success_rate * mean_p_success
    Ic_all = coherent_information_vectorized(F_final[used]) * p_success_all[used] if np.sum(used) > 0 else np.array([])
    std_Ic = np.std(Ic_all) if len(Ic_all) > 0 else 0.0
    total_success_prob = success_rate * mean_p_success
    return mean_Ic, std_Ic, F_mean, total_success_prob

def swap_then_distill(n_samples, lam, c, T, samples, swap_strategy, distill_strategy):
    t1a, t1b, t2a, t2b = samples['t_l1_1'], samples['t_l1_2'], samples['t_l2_1'], samples['t_l2_2']
    avail = state_availability(t1a, t1b, t2a, t2b, T)
    valid = avail >= 2
    F_final = np.zeros_like(t1a)
    p_success_all = np.ones(n_samples)
    used = valid.copy()

    for i in np.where(valid)[0]:
        link1_pairs = sorted([t for t in [t1a[i], t1b[i]] if t < T])
        link2_pairs = sorted([t for t in [t2a[i], t2b[i]] if t < T])
        all_times = sorted([t for t in [t1a[i], t1b[i], t2a[i], t2b[i]] if t < T])
        ready_l1, ready_l2 = len(link1_pairs), len(link2_pairs)

        if ready_l1 < 1 or ready_l2 < 1:
            used[i] = False
            continue

        p_success_total = 1.0

        if swap_strategy == 'ASAP':
            t_swap_1, t_swap_2 = link1_pairs[0], link2_pairs[0]
            t_swap = max(t_swap_1, t_swap_2)
            F1 = raw_fidelity(t_swap_1, t_swap, c)
            F2 = raw_fidelity(t_swap_2, t_swap, c)
            F_swap = swapped_fidelity(F1, F2)
            remaining = [t for t in all_times if t > t_swap]

            if distill_strategy == 'ASAP':
                if len(remaining) >= 1:
                    t_dist = remaining[0]
                    F_remain = raw_fidelity(remaining[0], t_dist, c)
                    F_swap_at_dist = compute_fidelity(F_swap, t_dist - t_swap, c)
                    F_dist = isotropic_purification_pairwise(F_swap_at_dist, F_remain)
                    p_success = F_swap_at_dist * F_remain + (1/3) * F_swap_at_dist * (1 - F_remain) + (1/3) * F_remain * (1 - F_swap_at_dist) + (5/9) * (1 - F_swap_at_dist) * (1 - F_remain)
                    p_success_total *= p_success
                    F_final[i] = compute_fidelity(F_dist, T - t_dist, c)
                else:
                    F_final[i] = compute_fidelity(F_swap, T - t_swap, c)
            else:
                F_swap_at_T = compute_fidelity(F_swap, T - t_swap, c)
                if len(remaining) >= 1:
                    F_remain = raw_fidelity(remaining[0], T, c)
                    F_final[i] = isotropic_purification_pairwise(F_swap_at_T, F_remain)
                    p_success = F_swap_at_T * F_remain + (1/3) * F_swap_at_T * (1 - F_remain) + (1/3) * F_remain * (1 - F_swap_at_T) + (5/9) * (1 - F_swap_at_T) * (1 - F_remain)
                    p_success_total *= p_success
                else:
                    F_final[i] = F_swap_at_T
        else:
            F1 = raw_fidelity(link1_pairs[0], T, c)
            F2 = raw_fidelity(link2_pairs[0], T, c)
            F_swap = swapped_fidelity(F1, F2)
            remaining = [t for t in all_times[2:] if t < T]

            if len(remaining) >= 1:
                F_remain = raw_fidelity(remaining[0], T, c)
                F_final[i] = isotropic_purification_pairwise(F_swap, F_remain)
                p_success = F_swap * F_remain + (1/3) * F_swap * (1 - F_remain) + (1/3) * F_remain * (1 - F_swap) + (5/9) * (1 - F_swap) * (1 - F_remain)
                p_success_total *= p_success
            else:
                F_final[i] = F_swap

        p_success_all[i] = p_success_total

    F_mean = np.mean(F_final[used]) if np.sum(used) > 0 else 0.0
    success_rate = np.sum(used) / n_samples
    mean_p_success = np.mean(p_success_all[used]) if np.sum(used) > 0 else 0.0
    mean_Ic = coherent_information_vectorized(F_mean) * success_rate * mean_p_success
    Ic_all = coherent_information_vectorized(F_final[used]) * p_success_all[used] if np.sum(used) > 0 else np.array([])
    std_Ic = np.std(Ic_all) if len(Ic_all) > 0 else 0.0
    total_success_prob = success_rate * mean_p_success
    return mean_Ic, std_Ic, F_mean, total_success_prob


def raw_fidelity(t_gen, t_total, tau):
    A = 1/4
    B = F_INIT - A
    return np.clip(A + B * np.exp(-2 * (t_total - t_gen) / tau), 0, 1)

def compute_fidelity(F_init, t_idle, tau):
    A = 1/4
    B = F_init - A
    return np.clip(A + B * np.exp(-2 * t_idle / tau), 0, 1)

def isotropic_purification_pairwise(F1, F2, p_gate=1.0, p_meas=1.0):
    """
    Entanglement purification with optional operation errors (Werner states).
    Returns (F_out, p_success) tuple.
    When p_gate=1.0, p_meas=1.0: uses original formula
    When imperfect: uses Paper Equations (8) and (9)
    """
    e1 = (1 - F1) / 3
    e2 = (1 - F2) / 3

    if p_gate == 1.0 and p_meas == 1.0:
        num = F1 * F2 + (1/9) * (1 - F1) * (1 - F2)
        denom = (F1 * F2 + (1/3) * F1 * (1 - F2) + (1/3) * F2 * (1 - F1) +
                 (5/9) * (1 - F1) * (1 - F2))
        F_out = np.clip(num / denom, 0, 1)
        p_success = denom
    else:
        eta = p_meas
        p = p_gate

        p_success = (p**2 * (eta**2 + (1 - eta)**2) *
                     (F1*F2 + F1*e2 + e1*F2 + 5*e1*e2) +
                     2 * p**2 * eta * (1 - eta) *
                     (2*F1*e2 + 2*e1*F2 + 4*e1*e2) +
                     (1 - p**2) / 2)

        numerator = ((eta**2 + (1 - eta)**2) * (F1*F2 + e1*e2) +
                     2 * eta * (1 - eta) * (F1*e2 + e1*e2) +
                     (1 - p**2) / (8 * p**2))

        denominator = ((eta**2 + (1 - eta)**2) *
                       (F1*F2 + F1*e2 + e1*F2 + 5*e1*e2) +
                       2 * eta * (1 - eta) *
                       (2*F1*e2 + 2*e1*F2 + 4*e1*e2) +
                       (1 - p**2) / (2 * p**2))

        F_out = np.clip(numerator / denominator, 0, 1)

    return F_out, p_success

def shared_bin_edges(*datasets, bins=60):
    pooled = np.concatenate([np.asarray(d).ravel() for d in datasets
                             if np.asarray(d).size > 0])
    if pooled.size == 0:
        return np.linspace(0.0, 1.0, bins + 1)
    lo, hi = float(pooled.min()), float(pooled.max())
    if hi <= lo:
        hi = lo + 1e-9
    return np.linspace(lo, hi, bins + 1)


def coherent_information_vectorized(F):
    λ1 = F
    λ_rest = (1 - F) / 3
    eigs = np.stack([λ1, λ_rest, λ_rest, λ_rest], axis=-1)
    S = -np.sum(eigs * np.log2(eigs + 1e-12), axis=-1)
    return np.maximum(0, 1 - S)

def generate_poisson_arrivals(lam, T, n_samples):
    X = np.random.exponential(1/lam, n_samples)
    X[X > T] = np.inf
    return X

def single_link_discard_oldest(n_samples, lam, tau, T, samples, p_gate=1.0, p_meas=1.0):
    t1a, t2a = samples['t_l1_1'], samples['t_l2_1']
    F_final = np.zeros(n_samples)
    used = np.zeros(n_samples, dtype=bool)

    for i in range(n_samples):
        available = [t for t in [t1a[i], t2a[i]] if t < T]
        if len(available) > 0:
            F_final[i] = raw_fidelity(max(available), T, tau)
            used[i] = True

    F_mean = np.mean(F_final[used]) if np.sum(used) > 0 else 0.0
    success_rate = np.sum(used) / n_samples
    mean_Ic = coherent_information_vectorized(F_mean) * success_rate
    std_Ic = 0.0

    return mean_Ic, std_Ic, F_mean, success_rate

def single_link_distill_asap(n_samples, lam, tau, T, samples, p_gate=1.0, p_meas=1.0):
    t1a, t2a = samples['t_l1_1'], samples['t_l2_1']
    F_final = np.zeros(n_samples)
    used = np.zeros(n_samples, dtype=bool)
    p_success_all = np.ones(n_samples)

    for i in range(n_samples):
        if t1a[i] < T and t2a[i] < T:
            t_dist = max(t1a[i], t2a[i])
            F1 = raw_fidelity(t1a[i], t_dist, tau)
            F2 = raw_fidelity(t2a[i], t_dist, tau)
            F_pur, p_succ = isotropic_purification_pairwise(F1, F2, p_gate, p_meas)
            F_final[i] = compute_fidelity(F_pur, T - t_dist, tau)
            used[i] = True
            p_success_all[i] = p_succ
        elif t1a[i] < T:
            F_final[i] = raw_fidelity(t1a[i], T, tau)
            used[i] = True
        elif t2a[i] < T:
            F_final[i] = raw_fidelity(t2a[i], T, tau)
            used[i] = True

    # NOTE (correction): F_mean must be the fidelity conditioned on actual
    # protocol success, i.e. weighted by each realization's purification
    # success probability p_success_all[i] (which is 1.0 for the single-arrival
    # cases and equal to the CNOT-distillation success probability for the
    # two-arrival cases). The original code used a plain unweighted mean over
    # "used" realizations, then separately multiplied Ic by mean(p_success),
    # which biases F_mean toward realizations with low p_success just as much
    # as those with high p_success, even though low-p_success realizations
    # contribute less to the actual (weighted) ensemble of successful outcomes.
    F_mean = (np.sum(p_success_all[used] * F_final[used]) / np.sum(p_success_all[used])
              if np.sum(used) > 0 else 0.0)
    p_success_mean = np.mean(p_success_all[used]) if np.sum(used) > 0 else 0.0
    success_rate = np.sum(used) / n_samples
    mean_Ic = coherent_information_vectorized(F_mean) * success_rate * p_success_mean
    std_Ic = 0.0

    return mean_Ic, std_Ic, F_mean, success_rate


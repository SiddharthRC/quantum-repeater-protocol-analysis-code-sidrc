def coherent_information(F):
    F = np.clip(F, 1e-12, 1 - 1e-12)
    lambda1 = F
    lambda_rest = (1 - F) / 3
    eigs = np.array([lambda1, lambda_rest, lambda_rest, lambda_rest])
    S = -np.sum(eigs * np.log2(eigs + 1e-12))
    return np.maximum(0, 1 - S)

def coherent_information_vectorized(F):
    λ1 = F
    λ_rest = (1 - F) / 3
    eigs = np.stack([λ1, λ_rest, λ_rest, λ_rest], axis=-1)
    S = -np.sum(eigs * np.log2(eigs + 1e-12), axis=-1)
    return np.maximum(0, 1 - S)

def raw_fidelity(t_gen, t_total, c, F_init=0.9):
    A = 1/4
    B = F_init - A
    return np.clip(A + B * np.exp(-2 * (t_total - t_gen) / c), 0, 1)

def compute_fidelity(F_init, t_idle, c):
    A = 1/4
    B = F_init - A
    return np.clip(A + B * np.exp(-2 * t_idle / c), 0, 1)

def isotropic_purification_pairwise(F1, F2):
    num = F1 * F2 + (1/9) * (1 - F1) * (1 - F2)
    denom = (F1 * F2 + (1/3) * F1 * (1 - F2) + (1/3) * F2 * (1 - F1) + (5/9) * (1 - F1) * (1 - F2))
    return np.clip(num / denom, 0, 1)

def swapped_fidelity(F1, F2):
    return np.clip(F1 * F2 + (1 - F1) * (1 - F2) / 3, 0, 1)

def state_availability(t1a, t1b, t2a, t2b, T):
    available = np.zeros(len(t1a), dtype=int)
    available += (t1a < T).astype(int) + (t1b < T).astype(int) + (t2a < T).astype(int) + (t2b < T).astype(int)
    return available

def discard_oldest_analytical(lam, c, T, F0=0.9):
    eps = 1e-8
    expLT = np.exp(-lam * T)
    exp2LT = np.exp(-2 * lam * T)
    exp2Tc = np.exp(-2 * T / c)
    F0_eff = F0 - 0.25

    term1 = 0.25 - 0.25 * exp2LT
    coeff = 2 * lam * F0_eff

    denom1 = lam - 2/c
    if abs(denom1) < eps:
        bracket1 = T * (expLT + 1) * exp2Tc
    else:
        bracket1 = (expLT + 1) * (exp2Tc - expLT) / denom1

    denom2 = 2*lam - 2/c
    if abs(denom2) < eps:
        bracket2 = T * exp2Tc
    else:
        bracket2 = (exp2Tc - exp2LT) / denom2

    term2 = coeff * (bracket1 - bracket2)

    Fbar = (term1 + term2) / (1 - exp2LT + eps)
    Fbar = np.clip(Fbar, 0, 1)
    success_rate = 1 - exp2LT
    R = success_rate * coherent_information(Fbar)

    return Fbar, R, success_rate


def recurrence_yield(F0, n_raw=4000, rounds=5, p_gate=1.0, p_meas=1.0):
    arr = np.full(n_raw, F0)
    for _ in range(rounds):
        if len(arr) < 2:
            break
        idx = np.random.permutation(len(arr))
        if len(idx) % 2:
            idx = idx[:-1]
        p = idx.reshape(-1, 2)
        F_purif, _ = isotropic_purification_pairwise(arr[p[:,0]], arr[p[:,1]], p_gate, p_meas)
        arr = F_purif
    return len(arr)/n_raw

